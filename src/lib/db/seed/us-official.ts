// ---------------------------------------------------------------------------
// Build + merge identical prompts across versions
// ---------------------------------------------------------------------------
type Built = {
  versions: Version[];
  raws: { v: Version; r: Raw }[];
};

function needSentence(v: Version | null, r: Raw): string {
  if (!r.need) return "";
  const list = (r.display ?? r.a).join("; ");
  const prefix = v ? `On the ${v} test` : "On the real test";
  return `${prefix}, name ${NUM_WORDS[r.need]} of: ${list}.`;
}

function build(): SeedQuestion[] {
  const byPrompt = new Map<string, Built>();
  const order: string[] = [];
  for (const [v, list] of [
    ["2025", q2025],
    ["2008", q2008],
  ] as const) {
    for (const r of list) {
      const existing = byPrompt.get(r.p);
      if (existing) {
        existing.versions.push(v);
        existing.raws.push({ v, r });
      } else {
        byPrompt.set(r.p, { versions: [v], raws: [{ v, r }] });
        order.push(r.p);
      }
    }
  }

  return order.map((prompt) => {
    const { versions, raws } = byPrompt.get(prompt)!;
    const primary = raws[0].r;
    const merged = raws.length > 1;

    const answers = [...new Set(raws.flatMap(({ r }) => r.a.flatMap(expand)))];

    const tags = new Set<string>();
    for (const { v, r } of raws) {
      for (const t of r.tags ?? []) tags.add(t);
      if (r.star) {
        tags.add("65-20");
        tags.add(`65-20:${v}`);
      }
    }

    const base = (raws.find(({ r }) => r.e)?.r.e ?? "").trim();
    const needs = raws.filter(({ r }) => r.need);
    const needText =
      needs.length === 1 && !merged
        ? needSentence(null, needs[0].r)
        : needs.map(({ v, r }) => needSentence(v, r)).join(" ");
    const explanation = [base, needText].filter(Boolean).join(" ");

    const q: SeedQuestion = {
      countryCode: "us",
      versions,
      chapterSlug: primary.ch,
      type: "shorttext",
      prompt,
      acceptedAnswers: answers,
      explanation,
      sourceRef: raws.map(({ v, r }) => `USCIS ${v} Civics Test, question ${r.n}`).join("; "),
    };
    if (tags.size) q.tags = [...tags];
    return q;
  });
}

export const usQuestions: SeedQuestion[] = build();

export const usQuestionCounts = {
  "2025": usQuestions.filter((q) => q.versions.includes("2025")).length,
  "2008": usQuestions.filter((q) => q.versions.includes("2008")).length,
};
