import type { Metadata } from "next";
import { SITE_NAME } from "./schema";

export function truncate(text: string, max: number): string {
  if (text.length <= max) return text;
  const cut = text.slice(0, max - 1);
  const lastSpace = cut.lastIndexOf(" ");
  return `${(lastSpace > 0 ? cut.slice(0, lastSpace) : cut).trimEnd()}…`;
}

/** Suffix added by the root layout's `title.template`. */
export const TITLE_SUFFIX = ` | ${SITE_NAME}`;
/** Roughly what Google shows before truncating a title. */
export const TITLE_MAX = 60;
export const DESCRIPTION_MAX = 160;

/**
 * Appends the brand suffix only when the result still fits in a search result;
 * otherwise the page title is used on its own so the keywords are not cut off.
 */
export function pageTitle(title: string): Metadata["title"] {
  return title.length + TITLE_SUFFIX.length <= TITLE_MAX ? title : { absolute: title };
}

type Options = {
  title: string;
  path: string;
  description?: string;
  noindex?: boolean;
  type?: "website" | "article";
  publishedTime?: string | null;
  modifiedTime?: string | null;
};

/**
 * The share image generated by `app/opengraph-image.tsx`. Next.js only attaches it
 * automatically to pages that don't set `openGraph` themselves (metadata merges are
 * shallow), so pages using `buildMetadata` reference it explicitly.
 */
export const OG_IMAGE = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: `${SITE_NAME}: free citizenship test practice for the US, UK, Canada and Australia`,
};

/** Per-page metadata. Canonical URLs are relative; `metadataBase` makes them absolute. */
export function buildMetadata({
  title,
  path,
  description,
  noindex,
  type = "website",
  publishedTime,
  modifiedTime,
}: Options): Metadata {
  const desc = description ? truncate(description, DESCRIPTION_MAX) : undefined;
  return {
    title: pageTitle(title),
    description: desc,
    alternates: { canonical: path },
    openGraph: {
      title,
      description: desc,
      url: path,
      siteName: SITE_NAME,
      locale: "en",
      images: [OG_IMAGE],
      ...(type === "article"
        ? {
            type: "article",
            ...(publishedTime && { publishedTime }),
            ...(modifiedTime && { modifiedTime }),
          }
        : { type: "website" }),
    },
    twitter: { card: "summary_large_image", title, description: desc, images: [OG_IMAGE] },
    robots: noindex ? { index: false, follow: true } : undefined,
  };
}
